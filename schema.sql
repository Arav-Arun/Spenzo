-- Spenzo database. Run once against an empty Postgres (Neon, Supabase…). Safe to re-run.
--   uv run python scripts/setup_db.py   (or: psql "$DATABASE_URL" -f schema.sql)

-- Who the user is and what Spenzo remembers about them.
create table if not exists users (
  phone           text primary key,             -- +919876543210, or 'local' on an unlinked desktop
  name            text default '',
  monthly_income  numeric,
  salary_day      int check (salary_day between 1 and 31),
  facts           jsonb default '[]'::jsonb,     -- ["Riya is my flatmate", ...]
  nudges          boolean default true,
  session_version int default 0,                -- bump to sign out every dashboard
  created_at      timestamptz default now()
);

-- Spend: money in and out.
create table if not exists transactions (
  id          bigint generated by default as identity primary key,
  phone       text    not null,
  date        date    not null,
  kind        text    not null check (kind in ('expense', 'income')),
  amount      numeric not null check (amount > 0),   -- INR
  category    text    not null,
  description text    default '',                     -- "Uber", "Samosa chaat"
  note        text    default '',                     -- "Total 3000 split 3 ways", "5 USD at ₹94"
  tags        text[]  default '{}',
  created_at  timestamptz default now()
);
create index if not exists transactions_phone_date on transactions (phone, date);

create table if not exists budgets (
  phone         text    not null,
  category      text    not null,                     -- or 'Total'
  monthly_limit numeric not null check (monthly_limit > 0),
  primary key (phone, category)
);

-- Split: who owes whom.
create table if not exists debts (
  id         bigint generated by default as identity primary key,
  phone      text    not null,
  person     text    not null,
  direction  text    not null check (direction in ('they_owe', 'i_owe')),
  amount     numeric not null check (amount > 0),
  reason     text    default '',
  date       date    not null,
  created_at timestamptz default now()
);
create index if not exists debts_phone on debts (phone);

-- Save: goals and investments.
create table if not exists goals (
  id         bigint generated by default as identity primary key,
  phone      text    not null,
  name       text    not null,
  target     numeric not null check (target > 0),
  saved      numeric not null default 0,
  deadline   date,
  created_at timestamptz default now()
);

create table if not exists holdings (
  id         bigint generated by default as identity primary key,
  phone      text    not null,
  kind       text    not null check (kind in ('stock', 'mutual_fund', 'crypto_wallet')),
  symbol     text    not null,                      -- TCS.NS · mfapi scheme code · wallet address
  name       text    not null,
  quantity   numeric not null default 0,            -- shares or units (unused for wallets)
  avg_price  numeric,                               -- what the user paid per unit, if known
  created_at timestamptz default now(),
  unique (phone, kind, symbol)
);

-- Conversation memory and nudge bookkeeping.
create table if not exists messages (
  id         bigint generated by default as identity primary key,
  phone      text not null,
  role       text not null check (role in ('user', 'assistant')),
  content    text not null,
  created_at timestamptz default now()
);
create index if not exists messages_phone_time on messages (phone, created_at desc);

create table if not exists nudges_sent (
  phone   text not null,
  key     text not null,                            -- 'budget80:Food & Dining'
  period  text not null,                            -- '2026-11', or 'once'
  sent_at timestamptz default now(),
  primary key (phone, key, period)
);

-- Linking Claude Desktop: Claude shows a code, the user sends "link <code>" on WhatsApp.
create table if not exists link_codes (
  code       text primary key,
  phone      text,                                  -- filled in when the WhatsApp message arrives
  expires_at timestamptz not null
);

-- Only matters on hosts that expose tables over a public API (like Supabase): lock them.
-- Spenzo connects as the owner, which row-level security doesn't restrict.
do $$ declare t text; begin
  foreach t in array array['users','transactions','budgets','debts','goals','holdings','messages','nudges_sent','link_codes']
  loop execute format('alter table %I enable row level security', t); end loop;
end $$;
